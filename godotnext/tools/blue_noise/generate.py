#!/usr/bin/env python3
"""Generate the NextGI blue-noise tile (#54, plan section 8.6).

Void-and-cluster ordering (Ulichney) on a 64x64 periodic grid, two independent channels.
Original implementation; no third-party noise textures (clean-room rule, plan section 19).

    python3 godotnext/tools/blue_noise/generate.py

Writes servers/rendering/renderer_rd/environment/nextgi_blue_noise.h.
"""

import os

import numpy as np

SIZE = 64
SIGMA = 1.5
SEEDS = (1, 2)

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "..", "servers", "rendering", "renderer_rd", "environment", "nextgi_blue_noise.h")


def kernel() -> np.ndarray:
    coords = np.arange(SIZE, dtype=np.float64)
    dx = np.abs(coords[:, None] - coords[None, :])
    dx = np.minimum(dx, SIZE - dx)
    dy = dx.T
    return np.exp(-(dx * dx + dy * dy) / (2.0 * SIGMA * SIGMA))


def rank_tile(seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    field = np.zeros((SIZE, SIZE), dtype=np.float64)
    ranks = np.full((SIZE, SIZE), -1, dtype=np.int32)
    kernel_weights = kernel()
    ny, nx = np.mgrid[0:SIZE, 0:SIZE]
    for step in range(SIZE * SIZE):
        # Largest void: the lowest energy on the periodic grid, ties broken by the rng.
        noise = rng.random((SIZE, SIZE))
        score = field + noise * 1e-6
        y, x = np.unravel_index(np.argmin(score), score.shape)
        ranks[y, x] = step
        # Add this point's periodic Gaussian contribution.
        field += np.roll(kernel_weights, (y, x), axis=(0, 1))
    return ranks


def main() -> None:
    tiles = []
    for seed in SEEDS:
        ranks = rank_tile(seed)
        values = np.floor(ranks * 256.0 / float(SIZE * SIZE)).astype(np.uint8)
        tiles.append(values)
