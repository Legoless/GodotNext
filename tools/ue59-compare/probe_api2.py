import unreal

subsys = unreal.get_engine_subsystem(unreal.SubobjectDataSubsystem)
actor_sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
a = actor_sub.spawn_actor_from_class(unreal.Actor, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
handles = subsys.k2_gather_subobject_data_for_instance(a)
print("HANDLES", len(handles))
params = unreal.AddNewSubobjectParams(parent_handle=handles[0], new_class=unreal.HierarchicalInstancedStaticMeshComponent)
nh, reason = subsys.add_new_subobject(params)
print("ADD_SUBOBJECT", nh, reason)
data = unreal.SubobjectDataBlueprintFunctionLibrary.get_data(nh)
obj = unreal.SubobjectDataBlueprintFunctionLibrary.get_object(data)
print("HISM_OBJ", type(obj), hasattr(obj, "add_instances"), hasattr(obj, "set_static_mesh"))

# Check LevelSequence & CameraCut & TransformTrack API
asset_tools = unreal.AssetToolsHelpers.get_asset_tools()
if unreal.EditorAssetLibrary.does_asset_exist("/Game/Ports/_ProbeSeq"):
    unreal.EditorAssetLibrary.delete_asset("/Game/Ports/_ProbeSeq")
seq = asset_tools.create_asset("_ProbeSeq", "/Game/Ports", unreal.LevelSequence, unreal.LevelSequenceFactoryNew())
print("SEQ_METHODS", [m for m in dir(seq) if any(k in m for k in ("track", "possess", "playback", "display", "frame"))])
cam = actor_sub.spawn_actor_from_class(unreal.CineCameraActor, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
cb = seq.add_possessable(cam)
print("CB_METHODS", [m for m in dir(cb) if any(k in m for k in ("track", "binding", "id"))])
tr = cb.add_track(unreal.MovieScene3DTransformTrack)
sec = tr.add_section()
print("SEC_CH", len(sec.get_all_channels()), [type(c).__name__ for c in sec.get_all_channels()[:3]])
ct = seq.add_track(unreal.MovieSceneCameraCutTrack)
csec = ct.add_section()
print("CSEC_METHODS", [m for m in dir(csec) if "bind" in m or "cam" in m or "range" in m])

# Check Light & SkyLight & Fog & PPV properties
dl = actor_sub.spawn_actor_from_class(unreal.DirectionalLight, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
pl = actor_sub.spawn_actor_from_class(unreal.PointLight, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
sp = actor_sub.spawn_actor_from_class(unreal.SpotLight, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
rl = actor_sub.spawn_actor_from_class(unreal.RectLight, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
sl = actor_sub.spawn_actor_from_class(unreal.SkyLight, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
fg = actor_sub.spawn_actor_from_class(unreal.ExponentialHeightFog, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
ppv = actor_sub.spawn_actor_from_class(unreal.PostProcessVolume, unreal.Vector(0,0,0), unreal.Rotator(0,0,0))
print("DL", hasattr(dl, "light_component"), [m for m in dir(dl.light_component) if "shadow" in m or "intens" in m or "color" in m][:10])
print("PL", hasattr(pl, "point_light_component"), hasattr(sp, "spot_light_component"), hasattr(rl, "rect_light_component"))
print("SL", hasattr(sl, "light_component"), [m for m in dir(sl.light_component) if "cube" in m or "source" in m or "real" in m][:10])
print("FG", hasattr(fg, "component"), [m for m in dir(fg.component) if "volumetric" in m or "density" in m][:10])
pps = ppv.get_editor_property("settings")
print("PPV_ML", [m for m in dir(pps) if "mega" in m.lower() or "lumen" in m.lower() or "global_ill" in m.lower() or "reflection_m" in m.lower()][:15])
print("PROBE2_OK")
